#!/usr/bin/env python3
"""Write the cumulative ablation configs and the empty results table.

    python benchmark/ablation/make_configs.py

Reads steps.json and the final configuration it names. Step N is the final
configuration with every switch of steps N+1.. reset to its off value, so
step 27 equals the final configuration and step 0 has every optimisation
off. Writes configs/ablation/sNN-<slug>.toml and benchmark/ablation/RESULTS.md.
Deterministic; rerunning rewrites byte-identical files. Each run then uses one
of these files with the standard launch command; nothing here runs a server.
"""
from __future__ import annotations

import dataclasses
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))

from muxserve.config import DeploymentConfig, config_to_toml, load_config, read_config_file  # noqa: E402

# Off value where the dataclass default is the optimised behaviour.
OFF_OVERRIDES = {"rpc_persistent_connections": False}


def off_value(name: str):
    if name in OFF_OVERRIDES:
        return OFF_OVERRIDES[name]
    field = {f.name: f for f in dataclasses.fields(DeploymentConfig)}[name]
    if field.default is not dataclasses.MISSING:
        value = field.default
    else:
        value = field.default_factory()
    return list(value) if isinstance(value, tuple) else value


def final_value(final: dict, name: str):
    if name in final:
        return final[name]
    return off_value(name) if name not in OFF_OVERRIDES else not OFF_OVERRIDES[name]


def main() -> None:
    plan = json.loads((HERE / "steps.json").read_text(encoding="utf-8"))
    final = read_config_file(ROOT / plan["final_config"])
    steps = plan["steps"]
    assert [s["id"] for s in steps] == list(range(1, len(steps) + 1))
    switches = [name for step in steps for name in step["switches"]]
    assert len(switches) == len(set(switches)), "a switch belongs to one step"
    baseline = plan["fixed_settings"]["baseline_switches"]
    fixed = set(final) - set(switches) - {"models"}
    for name in fixed - set(baseline):
        pass  # every other final setting is kept in all steps
    # Every final setting that differs from its default must be a step switch,
    # a baseline switch or a declared fixed setting.
    declared_fixed = {"tp_size", "kv_pool_mode", "kv_bytes_per_rank", "kv_memory_fraction", "extra_headroom_bytes_per_rank",
                      "max_model_inflight", "max_new_tokens", "request_timeout_ms", "gateway_connections",
                      "runtime_dir", "asset_lock_dir", "controller_port"}
    for name in fixed:
        if name in baseline or name in declared_fixed:
            continue
        assert final[name] == off_value(name), f"undeclared final setting {name}={final[name]!r}"

    out = ROOT / "configs" / "ablation"
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for number in range(0, len(steps) + 1):
        config = dict(final)
        for step in steps:
            for name in step["switches"]:
                if step["id"] <= number:
                    config[name] = final_value(final, name)
                else:
                    config[name] = off_value(name)
        slug = "baseline" if number == 0 else steps[number - 1]["slug"]
        path = out / f"s{number:02d}-{slug}.toml"
        relative = path.relative_to(ROOT).as_posix()
        header = (f"Patch ablation step {number} of {len(steps)} (benchmark/ablation/steps.json), "
                  "generated by benchmark/ablation/make_configs.py.\n"
                  f"Launch from the repository root:  uv run muxserve serve {relative}")
        path.write_bytes(config_to_toml(config, header).encode("utf-8"))
        load_config(path, require_assets=False)  # every step is a valid deployment
        rows.append((number, relative))
    assert read_config_file(ROOT / rows[-1][1]) == {
        **final, **{name: final_value(final, name) for name in switches}}

    lines = [
        "# 补丁消融结果（累加）",
        "",
        "由 `make_configs.py` 生成，数值列由实测填写；未实测的格子保持 `待测`，不得填估计值。",
        f"负载：xbench case `{plan['workload']['case']}`（{plan['workload']['summary']}）。",
        "每一步一次大实验（不开 TRACE / PROFILE），服务每步重新启动。",
        "",
        "| 步 | 提交 | 类型 | 打开的开关 | 配置 | 吞吐 tok/s | 相对上一步 | TTFT p50 / p99 ms | TPOT p50 / p99 ms | 完成 / 失败 |",
        "|---|---|---|---|---|---|---|---|---|---|",
        f"| 0 | — | 基线 | （全部关闭；含常开修复与 capacity_recovery_all_decode） | `{rows[0][1]}` | 待测 | — | 待测 | 待测 | 待测 |",
    ]
    kinds = {"performance": "性能", "original-parity": "原版对齐"}
    for step, (number, path) in zip(steps, rows[1:]):
        lines.append(f"| {number} | `{step['commit']}` | {kinds[step['kind']]} | "
                     f"{', '.join('`' + s + '`' for s in step['switches'])} | `{path}` | 待测 | 待测 | 待测 | 待测 | 待测 |")
    lines += ["", "## 每个补丁的动机与对模型适配的影响", "",
              "| 步 | 提交 | 类型 | 动机 | 对后续模型适配的影响 |", "|---|---|---|---|---|"]
    for step in steps:
        lines.append(f"| {step['id']} | `{step['commit']}` | {kinds[step['kind']]} | "
                     f"{step['motivation']} | {step['adaptation']} |")
    lines += ["", "## 基线里常开、不在表中单独计量的改动", "",
              "这些提交没有开关，包含在第 0 步里，所以表中没有它们各自的增量。", "",
              "| 提交 | 改动 |", "|---|---|"]
    for item in plan["always_on"]:
        lines.append(f"| `{item['commit']}` | {item['change']} |")
    for name, item in plan["fixed_settings"]["baseline_switches"].items():
        lines.append(f"| `{item['commit']}` | `{name}`（基线即打开）：{item['reason']} |")
    (HERE / "RESULTS.md").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    for number, path in rows:
        print(number, path)


if __name__ == "__main__":
    main()
