"""Verify, materialize, and patch the pinned SGLang source using Python 3.10+.

Use --archive sglang-v0.5.20-source.tar.gz for an offline bootstrap. No package
installation, Git checkout, GPU, or execution of upstream code is required.
Existing installed trees may contain .pyc-only __pycache__ directories and the
standard top-level python/sglang.egg-info files listed in EGG_INFO_FILES below.
This allowance supports installed trees; generated bytecode and metadata contents
are not attested by source verification.
"""
from __future__ import annotations

import argparse
from contextlib import redirect_stdout
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import ssl
import stat
import sys
import tarfile
import tempfile
from types import ModuleType
from urllib.parse import urlparse
from urllib.request import build_opener, HTTPRedirectHandler, HTTPSHandler, Request


ROOT = Path(__file__).absolute().parents[1]
COMMIT = "94602c9c2b7cbdb8efd5c52802dac6a1c180089e"
TAG = "v0.5.20"
ARCHIVE_SHA256 = "fcd78d64bcac43c5f31b0a99d7078540858b9c2f5c6782a484e3890c4dc07ae6"
ARCHIVE_SIZE = 32_412_974
SOURCE_FILE_COUNT = 9166
ARCHIVE_URL = f"https://codeload.github.com/sgl-project/sglang/tar.gz/{COMMIT}"
ARCHIVE_PREFIX = f"sglang-{COMMIT}"
# These links occur in the pinned archive. Validate their exact targets and omit
# them, matching extraction.json; never create links in the materialized source.
SKIPPED_LINKS = {
    ".dockerignore": ".gitignore",
    "python/sglang/srt/mem_cache/cpp_radix_tree/.clang-format": "../../../kernels/aot/.clang-format",
    "sgl-model-gateway/LICENSE": "../LICENSE",
}
CHUNK_SIZE = 1024 * 1024
EGG_INFO_DIRECTORY = "python/sglang.egg-info"
EGG_INFO_FILES = frozenset({
    "PKG-INFO", "SOURCES.txt", "dependency_links.txt", "entry_points.txt",
    "requires.txt", "top_level.txt", "namespace_packages.txt", "not-zip-safe", "zip-safe",
})


def _relative_name(name: str) -> str:
    """Accept canonical, portable POSIX paths only (including on Windows)."""
    if (
        not isinstance(name, str)
        or not name
        or "\\" in name
        or ":" in name
        or "\x00" in name
        or any(part in ("", ".", "..") for part in name.split("/"))
    ):
        raise RuntimeError(f"Unsafe source path: {name!r}")
    return name


def _no_links(path: Path) -> None:
    """Reject symlinks and Windows junction/reparse points in every ancestor."""
    for current in reversed((path, *path.parents)):
        try:
            info = current.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise RuntimeError(f"Source path contains a link or reparse point: {current}")


def _hash_file(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(CHUNK_SIZE), b""):
            hasher.update(block)
    return hasher.hexdigest()


def _directories(files: dict[str, str]) -> set[str]:
    return {str(parent) for name in files for parent in PurePosixPath(name).parents if str(parent) != "."}


def _json_file(root: Path, name: str) -> dict:
    path = root / "upstream-reference" / name
    _no_links(path)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RuntimeError(f"Cannot read source manifest {name}: {exc}") from exc
    if not isinstance(value, dict):
        raise RuntimeError(f"Invalid source manifest: {name}")
    return value


def _digest(value: object) -> str:
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None:
        raise RuntimeError("Source manifest contains an invalid SHA-256 hash")
    return value


def _metadata(root: Path) -> tuple[dict[str, str], dict, list[dict]]:
    extraction = _json_file(root, "extraction.json")
    if (
        extraction.get("commit") != COMMIT
        or extraction.get("tag") != TAG
        or extraction.get("archive_sha256") != ARCHIVE_SHA256
        or extraction.get("files") != SOURCE_FILE_COUNT
    ):
        raise RuntimeError("Extraction manifest differs from the pinned SGLang archive")
    files = extraction.get("files_sha256")
    if not isinstance(files, dict) or len(files) != SOURCE_FILE_COUNT:
        raise RuntimeError("Extraction manifest has an invalid regular-file count")
    canonical = {_relative_name(name): _digest(value) for name, value in files.items()}
    if len({name.casefold() for name in canonical}) != len(canonical):
        raise RuntimeError("Extraction manifest contains colliding source paths")
    links = extraction.get("skipped_links")
    if not isinstance(links, list) or len(links) != len(SKIPPED_LINKS):
        raise RuntimeError("Extraction manifest has unexpected skipped links")
    if any(not isinstance(item, dict) or SKIPPED_LINKS.get(item.get("path")) != item.get("target") for item in links):
        raise RuntimeError("Extraction manifest has unexpected skipped links")
    if {item["path"] for item in links} != set(SKIPPED_LINKS):
        raise RuntimeError("Extraction manifest repeats skipped links")
    patches = _json_file(root, "patches.json")
    for name, patch in patches.items():
        _relative_name(name)
        if not isinstance(patch, dict) or patch.get("source_sha256") != canonical.get(name):
            raise RuntimeError(f"Patch manifest source mismatch: {name}")
        _digest(patch.get("patched_sha256"))
    packaging = _json_file(root, "packaging-additions.json")
    additions = packaging.get("additions")
    if packaging.get("sglang_commit") != COMMIT or not isinstance(additions, list):
        raise RuntimeError("Packaging manifest differs from the pinned source")
    required = {"python/README.md": "README.md", "python/LICENSE": "LICENSE"}
    if len(additions) != len(required):
        raise RuntimeError("Packaging manifest must contain the two Python metadata copies")
    observed = set()
    for item in additions:
        if not isinstance(item, dict):
            raise RuntimeError("Invalid packaging addition")
        name, source = _relative_name(item.get("path")), _relative_name(item.get("source"))
        if required.get(name) != source or name in canonical or name in observed:
            raise RuntimeError(f"Unrecognized packaging addition path: {name}")
        if _digest(item.get("sha256")) != canonical.get(source):
            raise RuntimeError(f"Packaging source hash mismatch: {name}")
        observed.add(name)
    return canonical, patches, additions


class _HTTPSOnlyRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        parsed = urlparse(newurl)
        if parsed.scheme != "https" or parsed.hostname != "codeload.github.com":
            raise RuntimeError("Refusing archive redirect outside the official HTTPS host")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _copy_archive(source, destination: Path) -> None:
    count = 0
    with destination.open("xb") as output:
        for block in iter(lambda: source.read(CHUNK_SIZE), b""):
            count += len(block)
            if count > ARCHIVE_SIZE:
                raise RuntimeError("Archive size exceeds the pinned size")
            output.write(block)


def _download_archive(destination: Path) -> None:
    opener = build_opener(HTTPSHandler(context=ssl.create_default_context()), _HTTPSOnlyRedirect())
    request = Request(ARCHIVE_URL, headers={"User-Agent": "paper-source-bootstrap/1.0"})
    with opener.open(request, timeout=60) as response:
        _copy_archive(response, destination)


def _extract_archive(archive: Path, destination: Path, expected: dict[str, str]) -> None:
    seen: set[str] = set()
    files: set[str] = set()
    links: set[str] = set()
    directories = _directories(expected)
    with tarfile.open(archive, "r:gz") as source:
        for member in source:
            name = member.name.rstrip("/") if member.isdir() else member.name
            _relative_name(name)
            if name == ARCHIVE_PREFIX:
                if not member.isdir() or name.casefold() in seen:
                    raise RuntimeError("Archive has an invalid or duplicate root directory")
                seen.add(name.casefold())
                continue
            if not name.startswith(ARCHIVE_PREFIX + "/"):
                raise RuntimeError(f"Archive has an unexpected source prefix: {name}")
            relative = _relative_name(name[len(ARCHIVE_PREFIX) + 1:])
            key = name.casefold()
            if key in seen:
                raise RuntimeError(f"Archive has a duplicate source path: {relative}")
            seen.add(key)
            if member.issym() and SKIPPED_LINKS.get(relative) == member.linkname:
                links.add(relative)
                continue
            if not member.isdir() and not member.isfile():
                raise RuntimeError(f"Archive contains a forbidden link or special file: {relative}")
            path = destination.joinpath(*relative.split("/"))
            if member.isdir():
                if relative not in directories:
                    raise RuntimeError(f"Archive contains an unexpected directory: {relative}")
                path.mkdir(parents=True, exist_ok=True)
                continue
            if relative not in expected or member.issparse():
                raise RuntimeError(f"Archive contains an unexpected regular file: {relative}")
            path.parent.mkdir(parents=True, exist_ok=True)
            reader = source.extractfile(member)
            if reader is None:
                raise RuntimeError(f"Archive cannot read regular file: {relative}")
            with reader, path.open("xb") as output:
                shutil.copyfileobj(reader, output, CHUNK_SIZE)
            if _hash_file(path) != expected[relative]:
                raise RuntimeError(f"Source integrity hash mismatch: {relative}")
            # Preserve executable scripts, without trusting ownership or special bits.
            path.chmod(0o644 | (member.mode & 0o111))
            files.add(relative)
    if files != set(expected) or links != set(SKIPPED_LINKS):
        raise RuntimeError("Archive is missing manifest files or the pinned skipped links")


def _installed_artifact(name: str, *, directory: bool, source_directories: set[str]) -> bool:
    """Bound generated artifacts to known directories, without admitting code."""
    path = PurePosixPath(name)
    if name == EGG_INFO_DIRECTORY:
        return directory
    if str(path.parent) == EGG_INFO_DIRECTORY:
        return not directory and path.name in EGG_INFO_FILES
    if directory:
        return path.name == "__pycache__" and str(path.parent) in source_directories | {"."}
    return (
        path.parent.name == "__pycache__"
        and str(path.parent.parent) in source_directories | {"."}
        and path.suffix == ".pyc"
    )


def _verify_tree(directory: Path, expected: dict[str, str], *, installed: bool = False) -> None:
    _no_links(directory)
    if not directory.is_dir():
        raise RuntimeError("Source destination is not a directory")
    observed = set()
    allowed_directories = _directories(expected)

    def fail(error: OSError) -> None:
        raise RuntimeError(f"Cannot inspect source tree: {error}") from error

    for current, directories, files in os.walk(directory, followlinks=False, onerror=fail):
        base = Path(current)
        for name in (*directories, *files):
            path = base / name
            info = path.lstat()
            relative = path.relative_to(directory).as_posix()
            if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
                raise RuntimeError(f"Source contains a link or reparse point: {relative}")
            if stat.S_ISDIR(info.st_mode):
                if relative not in allowed_directories and not (
                    installed and _installed_artifact(relative, directory=True, source_directories=allowed_directories)
                ):
                    raise RuntimeError(f"Source contains an unexpected directory: {relative}")
                continue
            if not stat.S_ISREG(info.st_mode):
                raise RuntimeError(f"Source contains a special file: {relative}")
            if relative not in expected:
                if installed and _installed_artifact(relative, directory=False, source_directories=allowed_directories):
                    continue
                raise RuntimeError(f"Source contains an unexpected file: {relative}")
            if _hash_file(path) != expected[relative]:
                raise RuntimeError(f"Source integrity mismatch; refusing drift: {relative}")
            observed.add(relative)
    missing = set(expected) - observed
    if missing:
        raise RuntimeError(f"Source integrity check found missing file: {min(missing)}")


def _patch_source(root: Path, source: Path) -> None:
    path = root / "tools/patch_sglang.py"
    _no_links(path)
    module = ModuleType("_pinned_source_patcher")
    module.__file__ = str(path)
    # Compile the local source explicitly: an import loader could instead execute
    # cached bytecode with a matching source timestamp/size or hash header.
    exec(compile(path.read_bytes(), str(path), "exec"), module.__dict__)
    module.ROOT = root
    module.UPSTREAM = source
    with redirect_stdout(sys.stderr):
        module.apply()


def bootstrap(*, root: Path = ROOT, archive: Path | None = None) -> dict:
    root = Path(root).absolute()
    if os.name == "nt" and not str(root).startswith("\\\\?\\"):
        # Private staging adds depth to already-long upstream paths. Extended
        # native paths work without changing the user's Windows registry.
        name = str(root)
        root = Path("\\\\?\\UNC\\" + name[2:] if name.startswith("\\\\") else "\\\\?\\" + name)
    _no_links(root)
    if not root.is_dir() or ".." in root.parts:
        raise RuntimeError("Bootstrap repository root must be a canonical directory")
    files, patches, additions = _metadata(root)
    final = dict(files)
    final.update({name: patch["patched_sha256"] for name, patch in patches.items()})
    final.update({item["path"]: item["sha256"] for item in additions})
    parent = root / "third_party"
    destination = parent / "sglang"
    _no_links(destination)
    report = {
        "status": "verified",
        "destination": "third_party/sglang",
        "commit": COMMIT,
        "tag": TAG,
        "archive_sha256": ARCHIVE_SHA256,
        "regular_files": len(files),
        "patches": len(patches),
        "packaging_additions": len(additions),
        "verification_scope": "recorded source, patch target, and packaging hashes",
        "generated_artifacts": "permitted for installed trees; contents are not attested",
        "skipped_links": [{"path": name, "target": target} for name, target in SKIPPED_LINKS.items()],
    }
    if destination.exists():
        _verify_tree(destination, final, installed=True)
        return report
    parent.mkdir(exist_ok=True)
    lock = parent / ".sglang-bootstrap.lock"
    try:
        descriptor = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError as exc:
        raise RuntimeError("Another source bootstrap is running (.sglang-bootstrap.lock exists)") from exc
    os.close(descriptor)
    try:
        with tempfile.TemporaryDirectory(prefix=".sglang-bootstrap-", dir=parent) as temporary:
            work = Path(temporary)
            local_archive = work / "source.tar.gz"
            if archive is None:
                _download_archive(local_archive)
            else:
                with Path(archive).open("rb") as source:
                    _copy_archive(source, local_archive)
            if local_archive.stat().st_size != ARCHIVE_SIZE or _hash_file(local_archive) != ARCHIVE_SHA256:
                raise RuntimeError("Archive size or SHA-256 does not match the pinned source")
            staging = work / "sglang"
            staging.mkdir()
            _extract_archive(local_archive, staging, files)
            _verify_tree(staging, files)
            for item in additions:
                target = staging / item["path"]
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes((staging / item["source"]).read_bytes())
            _patch_source(root, staging)
            _verify_tree(staging, final)
            _no_links(destination)
            if destination.exists():
                raise RuntimeError("Source destination appeared during bootstrap; refusing to overwrite")
            staging.rename(destination)
        report["status"] = "materialized"
        return report
    finally:
        lock.unlink()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Use an explicit local sglang-v0.5.20-source.tar.gz (no download)")
    args = parser.parse_args()
    try:
        report = bootstrap(archive=args.archive)
    except (OSError, RuntimeError, tarfile.TarError) as exc:
        print(f"Source bootstrap failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
